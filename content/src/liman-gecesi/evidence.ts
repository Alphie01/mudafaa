// 20-evidence: deliller (EVIDENCE), ipuçları (CLUE) ve çıkarımlar (INSIGHT). Başlıklar bulunmadan önce hiçbir ekran
// metninde geçmez (LEAK); bu yüzden başlıklar düzyazıda kullanılmayan, belgeye özgü adlardır. `key` etiketi Delil
// toplama döküm satırına girer.

const c = (
  id: string,
  title: string,
  shortText: string,
  description: string,
  sourceLabel: string,
  extra: Partial<EvidenceDef> = {},
) =>
  clue(id, { type: 'BELGE', icon: 'magnifier', title, shortText, description, sourceLabel, tags: ['kart'], ...extra });

const d = (
  id: string,
  title: string,
  shortText: string,
  description: string,
  from: [string, string],
  extra: Partial<EvidenceDef> = {},
) =>
  insight(id, {
    type: 'BELGE',
    icon: 'bulb',
    side: 'DEFENSE',
    strength: 'STRONG',
    title,
    shortText,
    description,
    sourceLabel: `Çıkarım tahtası · ${from[0]} + ${from[1]}`,
    tags: ['key'],
    ...extra,
  });

